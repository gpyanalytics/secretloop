#!/usr/bin/env node
"use strict";
// Isolates the committed Windows runtime marker test WITHOUT touching the committed file (rev4).
// tests/harness.ts has no selection mechanism, so the block is copied VERBATIM -- hash and length
// verified against bound.json -- into tests/__win-red-runtime.test.ts under a synthesized header that
// imports exactly what the block references. The static marker tests are not in the extracted file,
// which is what lets a mutation reach the RUNTIME assertions.
//
// usage: node extract-runtime-test.js <copy-root> <bound.json>
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const [root, boundPath] = process.argv.slice(2);
if (!root || !boundPath) { console.log("EXTRACT-ERROR: usage <copy-root> <bound.json>"); process.exit(2); }
const bound = JSON.parse(fs.readFileSync(boundPath, "utf8"));
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const rel = "tests/consent-acl-win.test.ts";
const raw = fs.readFileSync(path.join(root, rel));
const lf = Buffer.from(raw.toString("utf8").replace(/\r\n/g, "\n"), "utf8");
if (sha(lf) !== bound.boundFiles[rel]) { console.log("EXTRACT-ERROR: " + rel + " does not match the bound hash"); process.exit(3); }
const lines = lf.toString("utf8").split("\n");
const start = lines.indexOf(bound.block.title);
if (start < 0) { console.log("EXTRACT-ERROR: runtime test title not found"); process.exit(4); }
let end = -1;
for (let i = start + 1; i < lines.length; i++) if (lines[i] === "});") { end = i; break; }
if (end < 0) { console.log("EXTRACT-ERROR: runtime test block end not found"); process.exit(5); }
const block = lines.slice(start, end + 1).join("\n") + "\n";
if (sha(Buffer.from(block, "utf8")) !== bound.block.sha256 || (end - start + 1) !== bound.block.lines) {
  console.log("EXTRACT-ERROR: runtime test block does not match the bound hash/length (" + (end - start + 1) + " lines)"); process.exit(6);
}
const header = [
  "// GENERATED BY win-red harness (rev4): the committed runtime marker test, isolated for RED validation.",
  "// Block copied verbatim from tests/consent-acl-win.test.ts lines " + (start + 1) + "-" + (end + 1) + ", sha256 " + bound.block.sha256 + ".",
  "// Header synthesized: only what the block references. The committed file is untouched.",
  'import { test, finish, assert, skip } from "./harness";',
  'import { mkdtempSync, rmSync, writeFileSync } from "fs";',
  'import { spawnSync } from "child_process";',
  'import { tmpdir } from "os";',
  'import * as path from "path";',
  'import * as acl from "../src/consent-acl-win";',
  'import { parseHelperMarkers, describeMarkers } from "./helper-markers";',
  'const WINDOWS = process.platform === "win32";',
  "",
].join("\n");
const out = header + block + "\nfinish();\n";
fs.writeFileSync(path.join(root, "tests", "__win-red-runtime.test.ts"), out);
console.log("EXTRACT-OK: block lines " + (start + 1) + "-" + (end + 1) + " (" + (end - start + 1) + " lines), block sha256 " + bound.block.sha256 + ", header " + (header.split("\n").length - 1) + " lines, written tests/__win-red-runtime.test.ts (" + out.length + " B)");
